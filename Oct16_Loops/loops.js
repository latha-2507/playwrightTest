
//loops in java script
//for loop
for (let i = 0; i < 5; i++) {
    console.log("The value of i is: " + i);
}

//while loop
let j = 0;
while (j < 5) {
    console.log("The value of j is: " + j);
    j++;
}

//do while loop
let k = 0;
do {
    console.log("The value of k is: " + k);
    k++;
} while (k < 5);

